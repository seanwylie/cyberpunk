#!/usr/bin/env python3
"""Give every music file a real fade-out ending (see tools/check_music_tails.py). Idempotent: files that pass are skipped.
- Hard loops: the current file is a seamless loop body B. New file = B + (the first 4.5 s of B, faded to silence) + 0.5 s silence.
  The tail continues the music exactly as the loop would, so listening to the file gives a natural fade, and in game the
  player loops sample-accurately at the loop point (len(B), written to src/music_loops.ts) and never reaches the fade.
- Everything else: a 4.5 s ring-out (the music keeps going under a light echo tail, padded where the file is short) fading to
  silence, then 0.5 s of silence. The original ending is kept up to where the fade starts.
Usage: python3 tools/fade_all.py [name ...]"""
import subprocess, sys, json, pathlib, re, importlib.util
ROOT = pathlib.Path(__file__).resolve().parent.parent; OUT = ROOT/'public'/'audio'/'music'; LOOPS = ROOT/'src'/'music_loops.ts'
spec = importlib.util.spec_from_file_location('c', ROOT/'tools'/'check_music_tails.py'); c = importlib.util.module_from_spec(spec); spec.loader.exec_module(c)
FADE, SIL = 4.5, 0.5
def br(f): return str(max(64, int(json.loads(subprocess.check_output(['ffprobe','-v','error','-show_entries','format=bit_rate','-of','json',str(f)]))['format']['bit_rate'])//1000//16*16))+'k'
def save_loops(LP):
    body = ',\n'.join(f'  {k}: {v:.6f}' for k, v in sorted(LP.items()))
    LOOPS.write_text("/** Generated by tools/fade_all.py: loop point (s) of each hard loop. The file continues past it into a faded tail\n * (so every file ends in a fade); the player loops 0..point sample-accurately and never plays the tail. */\nexport const LOOP_END: Record<string, number> = {\n" + body + "\n};\n")
def main(names):
    LP = c.loops(); fixed = []
    for n in names:
        f = OUT/f'{n}.mp3'; probs, _ = c.check(n, LP)
        if not probs: continue
        tmp = pathlib.Path('/tmp')/f'fa_{n}.mp3'; B = br(f); x = c.pcm(f); L = len(x)/44100; src = pathlib.Path('/tmp')/f'fa_src_{n}.mp3'; src.write_bytes(f.read_bytes())
        for k in (1, 2, 3):  # fade curve gets steeper (exp applied k times) until a loud passage inside the tail no longer bumps the fade
            FX = lambda st: ','.join([f'afade=t=out:st={st}:d={FADE}:curve=exp']*k); f_in = src
            if c.HARD(n):
                if n in LP: body = LP[n]  # already extended once: rebuild from its body
                else: body = L
                fc = (f"[0:a]asplit=2[a][b];[a]atrim=0:{body},asetpts=PTS-STARTPTS[m];[b]atrim=0:{FADE},asetpts=PTS-STARTPTS,"
                      f"{FX(0)},apad=pad_dur={SIL}[t];[m][t]concat=n=2:v=0:a=1[o]")
                subprocess.check_call(['ffmpeg','-y','-v','error','-i',str(f_in),'-filter_complex',fc,'-map','[o]','-ac','2','-ar','44100','-b:a',B,str(tmp)])
                LP[n] = body
            else:
                st = max(0.0, L-FADE*0.6)  # keep most of the ending; short files ring out under an echo tail
                fc = (f"[0:a]apad=pad_dur={FADE},aecho=0.8:0.6:90|180:0.35|0.2,atrim=0:{st+FADE},"
                      f"{FX(st)},apad=pad_dur={SIL}[o]")
                subprocess.check_call(['ffmpeg','-y','-v','error','-i',str(f_in),'-filter_complex',fc,'-map','[o]','-ac','2','-ar','44100','-b:a',B,str(tmp)])
            LPt = dict(LP)
            if not c.check_file(tmp, n, LPt)[0]: break
        tmp.replace(f); src.unlink(); fixed.append(n)
        p2, info = c.check(n, LP); print(('ok   ' if not p2 else 'STILL ')+n+' '+info+(' '+'; '.join(p2) if p2 else ''), flush=True)
        save_loops(LP)
    print(f'fixed {len(fixed)}'); return fixed
if __name__ == '__main__':
    main(sys.argv[1:] or sorted(p.stem for p in OUT.glob('*.mp3')))
