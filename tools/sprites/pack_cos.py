# Pack cosmetic layer renders (build_char.py with COS=slot:ids) -> public/sprites/cos/<id>/<anim>.webp + src/content/cosart.ts + icons.
# Usage: pack_cos.py RAW [RAW2 ...]   Cells match the body atlas (RES/2), same premultiplied downsample + thin outline as pack.py.
import sys, os, json, glob, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from PIL import Image, ImageFilter
ROOT=os.path.abspath(os.path.join(os.path.dirname(__file__),'..','..')); OUT=ROOT+'/public/sprites/cos'; DIRS=['S','SW','W','NW','N','NE','E','SE']
OL=(20,17,14)
def outline(im):
    al=im.split()[3]; ol=al.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(0.8)).point(lambda v:min(255,int(v*2.2*0.42)))
    dark=Image.new('RGBA',im.size,OL+(255,)); dark.putalpha(ol); return Image.alpha_composite(dark,im)
def down(im,cell): return im.convert('RGBa').resize((cell,cell),Image.LANCZOS).convert('RGBA')
for RAW in sys.argv[1:]:
    od=json.load(open(RAW+'/order.json'))
    for layer in od['layers']:
        iid=layer[4:]; os.makedirs(f'{OUT}/{iid}',exist_ok=True)
        for anim,rows in od['order'].items():
            n=len(rows[0]); first=f'{RAW}/{anim}/{layer}/S_0.png'
            if not os.path.exists(first): continue
            SRC=Image.open(first).width; cell=SRC//2; sheet=Image.new('RGBA',(cell*n,cell*8))
            for di,d in enumerate(DIRS):
                for f in range(n): sheet.paste(down(outline(Image.open(f'{RAW}/{anim}/{layer}/{d}_{f}.png').convert('RGBA')),cell),(f*cell,di*cell))
            sheet.save(f'{OUT}/{iid}/{anim}.webp',format='WEBP',lossless=True,method=5)
        print('packed',iid,flush=True)
ids=sorted(os.path.basename(p) for p in glob.glob(OUT+'/*') if os.path.exists(p+'/idle.webp'))
open(ROOT+'/src/content/cosart.ts','w').write('// GENERATED by tools/sprites/pack_cos.py: cosmetics that have real model layers (public/sprites/cos/<id>/). Do not edit.\nexport const COS_ART: ReadonlySet<string> = new Set([\n'+''.join(f"  '{i}',\n" for i in ids)+']);\n')
print('cosart',len(ids))
