# Pack cosmetic layer renders (build_char.py with COS=slot:ids) -> public/sprites/cos/<id>/<anim>.webp + src/content/cosart.ts + icons.
# Usage: pack_cos.py RAW [RAW2 ...]   Cells match the body atlas (RES/2), same premultiplied downsample + thin outline as pack.py.
import sys, os, json, glob, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from PIL import Image, ImageFilter
ROOT=os.path.abspath(os.path.join(os.path.dirname(__file__),'..','..')); OUT=ROOT+'/public/sprites/cos'; DIRS=['S','SW','W','NW','N','NE','E','SE']
OL=(20,17,14)
def outline(im):
    al=im.split()[3]; ol=al.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(0.8)).point(lambda v:min(255,int(v*2.2*0.42)))
    dark=Image.new('RGBA',im.size,OL+(255,)); dark.putalpha(ol); return Image.alpha_composite(dark,im)
def down(im,cell): return im.convert('RGBa').resize((cell,cell),Image.LANCZOS).convert('RGBA')
# item ids renamed after a render (COS_RENAME=old:new,...) are packed under the current id
RENAME=dict(x.split(':') for x in os.environ.get('COS_RENAME','').split(',') if ':' in x)
for RAW in sys.argv[1:]:
    od=json.load(open(RAW+'/order.json'))
    for layer in od['layers']:
        iid=RENAME.get(layer[4:],layer[4:]); os.makedirs(f'{OUT}/{iid}',exist_ok=True)
        for anim,rows in od['order'].items():
            n=len(rows[0]); first=f'{RAW}/{anim}/{layer}/S_0.png'
            if not os.path.exists(first): continue
            SRC=Image.open(first).width; cell=SRC//2; sheet=Image.new('RGBA',(cell*n,cell*8))
            for di,d in enumerate(DIRS):
                for f in range(n): sheet.paste(down(outline(Image.open(f'{RAW}/{anim}/{layer}/{d}_{f}.png').convert('RGBA')),cell),(f*cell,di*cell))
            sheet.save(f'{OUT}/{iid}/{anim}.webp',format='WEBP',lossless=True,method=5)
        print('packed',iid,flush=True)
ids=sorted(os.path.basename(p) for p in glob.glob(OUT+'/*') if os.path.exists(p+'/idle.webp'))
open(ROOT+'/src/content/cosart.ts','w').write('// GENERATED by tools/sprites/pack_cos.py: cosmetics that have real model layers (public/sprites/cos/<id>/). Do not edit.\nexport const COS_ART: ReadonlySet<string> = new Set([\n'+''.join(f"  '{i}',\n" for i in ids)+']);\n')
print('cosart',len(ids))
# ---- icons: the real piece on the body (idle, facing S then SE), recoloured, cropped around the piece -> <id>/icon.webp (96 px)
import numpy as np
items=json.load(open(os.environ.get('COS_ITEMS','/tmp/cos_items.json')))
def hx(h):
    h=h if len(h)==7 else '#'+''.join(ch*2 for ch in h[1:4]); return np.array([int(h[i:i+2],16)/255 for i in (1,3,5)])
def recolor(im,c,c2):
    a=np.asarray(im).astype(float)/255; R,G,B=a[...,0:1],a[...,1:2],a[...,2:3]; glow=np.minimum(1,hx(c2)*0.6+0.4); w=np.minimum(np.minimum(R,G),B)
    rgb=np.clip((R-w)*hx(c)+(G-w)*hx(c2)+(B-w)*glow+w,0,1); return Image.fromarray((np.concatenate([rgb,a[...,3:4]],-1)*255).astype('uint8'))
body=Image.open(ROOT+'/public/sprites/idle.webp').convert('RGBA')
for iid in ids:
    if iid not in items: continue
    sh=Image.open(f'{OUT}/{iid}/idle.webp').convert('RGBA'); cell=sh.height//8; di=7  # SE reads best for most pieces
    b=body.crop((0,di*cell,cell,(di+1)*cell)).resize((cell,cell)); p=recolor(sh.crop((0,di*cell,cell,(di+1)*cell)),items[iid]['c'],items[iid]['c2'])
    bb=p.split()[3].point(lambda v:255 if v>24 else 0).getbbox() or (0,0,cell,cell)
    cx,cy=(bb[0]+bb[2])/2,(bb[1]+bb[3])/2; half=max(bb[2]-bb[0],bb[3]-bb[1])/2*1.35+6
    t=Image.new('RGBA',(cell,cell)); t.alpha_composite(b); t.alpha_composite(p)
    t.crop((int(cx-half),int(cy-half),int(cx+half),int(cy+half))).resize((96,96),Image.LANCZOS).save(f'{OUT}/{iid}/icon.webp',format='WEBP',quality=90,alpha_quality=100)
print('icons',len(ids))
